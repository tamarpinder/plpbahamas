export const getLeaderboardByType = (type, constituency = null) => {
  switch (type) {
    case "national":
      return nationalLeaderboard;
    case "constituency":
      return constituency ? constituencyLeaderboards[constituency] || [] : [];
    case "squad":
      return squadLeaderboard;
    case "weekly":
      return weeklyLeaderboard;
    case "monthly":
      return monthlyLeaderboard;
    default:
      return nationalLeaderboard;
  }
};

export const getUserRank = (userId, leaderboard) => {
  const userEntry = leaderboard.find(entry => entry.user_id === userId);
  return userEntry ? userEntry.rank : null;
};